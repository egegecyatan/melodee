# The FMINI engine's factory bank for Melodee, from FMini-1 (Guilherme Ruppert, https://github.com/ruppert/fmini-1).
"""Write firmware/src/eng_fmini_bank.h from FMini-1's generated firmware/src/eng_fmini_presets.h.

FMini-1 keeps its 200 factory patches in three tables (FMINI_FACTORY: the 24 patch bytes, FMINI_PRESETS: the
preset_t rows with FMini-1's FX() and PAT() fields, FMINI_X: the arpeggiator, LFO, FX, level, modulation, octave).
Melodee reads one row per patch from the resource region (res.c), so they are merged into fmini_rom_t rows here.
Melodee keeps the first NSLOT (192): a track parameter is stored in one byte (-64..127), so SLOT (E7) holds slot - 64
and reaches 192 patches; FMini-1's last eight (FX: RAYGUN .. SUB DROP) are left out. FX and PAT (FMini-1's own effects and patterns), the arpeggiator and the octave are left out: in Melodee they are
the track's and the project's, not the sound's.

    python3 tools/gen_fmini_bank.py <fmini-1>/firmware/src/eng_fmini_presets.h [commit]
"""
import re
import sys
from pathlib import Path

FG_SIZE = 32
NSLOT = 192               # the slots SLOT reaches (eng_fmini.c FMINI_NSLOT)
NSRC = 200                # FMini-1's factory patches


def ints(s):
    return [int(x) for x in re.findall(r'-?\d+', s)]


def table(src, name):
    m = re.search(r'\b' + name + r'\b[^=]*=\s*\{(.*?)^\};', src, re.S | re.M)
    if not m:
        raise SystemExit(f'gen_fmini_bank: no {name}')
    return m[1]


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1]).read_text()
    commit = sys.argv[2] if len(sys.argv) > 2 else 'unknown'
    src_nc = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

    patches = [ints(m) for m in re.findall(r'FGP\(([^)]*)\)', table(src_nc, 'FMINI_FACTORY'))]
    rows = re.findall(r'\{\s*"([^"]*)"\s*,\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}\s*,\s*(-?\d+)\s*,\s*(\d+)\s*,',
                      table(src_nc, 'FMINI_PRESETS'))
    extras = re.findall(r'\{\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}\s*,\s*(\d+)\s*,\s*\{([^}]*)\}\s*,\s*(-?\d+)\s*\}',
                        table(src_nc, 'FMINI_X'))
    cats = re.search(r'#define FMINI_CATS "([A-Z]*)"', src)
    if not (len(patches) == len(rows) == len(extras) == NSRC and cats and len(cats[1]) == NSRC):
        raise SystemExit(f'gen_fmini_bank: {len(patches)} patches, {len(rows)} presets, {len(extras)} extras, '
                         f'{len(cats[1]) if cats else 0} categories (want {NSRC} each)')

    out = ['/* SPDX-License-Identifier: GPL-3.0-only',
           ' * Copyright (C) 2026 Guilherme Ruppert (FMini-1): the 200 factory patches.',
           f' * Generated by tools/gen_fmini_bank.py from FMini-1 {commit} firmware/src/eng_fmini_presets.h (do not edit by hand).',
           f' * The first {NSLOT} of its {NSRC}. A row: the patch (FG_ bytes, eng_fmini.c), the name, {{CUT EMPH CNTR F.ATK F.DEC F.SUS MOD',
           ' * SLOT (slot - 64)}, {ATK DEC SUS REL},',
           ' * ENV -> FILTER, MONO, the LFO {RATE WAVE FADE SYNC}, the level (P_LEVEL units: a trim against 104), the',
           ' * modulation {LFO>PITCH LFO>AMP ENV>PITCH}. */',
           '#ifndef MELODEE_RES',
           '#define MELODEE_RES  /* melodee.c: the resource region (res.c) */',
           '#endif',
           f'#define FMINI_CATS "{cats[1][:NSLOT]}"   /* browse.c PRESET_CAT: B bass, L lead, P pad, U pluck, K keys, F fx */',
           'static const fmini_rom_t FMINI_BANK[FMINI_NSLOT] MELODEE_RES = {']
    for k in range(NSLOT):
        g = patches[k]
        if len(g) > FG_SIZE:
            raise SystemExit(f'gen_fmini_bank: patch {k} has {len(g)} bytes')
        g = g + [0] * (FG_SIZE - len(g))
        name, e, env, fenv, mono = rows[k]
        e, env = ints(e), ints(env)
        if len(name) > 12 or len(e) != 8 or len(env) != 4 or e[7] != k:
            raise SystemExit(f'gen_fmini_bank: preset {k} ({name}) is not a slot row')
        e[7] = k - 64                                 # SLOT as stored (eng_fmini.c fmini_slot_of)
        _arp, lfo, _fx, level, mod, _oct = extras[k]
        lfo, mod = ints(lfo), ints(mod)
        out.append(f'    {{{{{", ".join(map(str, g))}}}, "{name}", {{{", ".join(map(str, e))}}}, '
                   f'{{{", ".join(map(str, env))}}}, {fenv}, {mono}, {{{", ".join(map(str, lfo))}}}, {level}, '
                   f'{{{", ".join(map(str, mod))}}}}},   /* {k:03d} */')
    out += ['};', '']
    root = Path(__file__).resolve().parent.parent
    dst = root / 'firmware/src/eng_fmini_bank.h'
    dst.write_text('\n'.join(out))
    print(f'fmini bank: {NSLOT} patches -> {dst}')

    # the web editor's mock device: the presets as the firmware makes them (eng_fmini.c fmini_preset_make: REL = DEC)
    js = []
    for k in range(NSLOT):
        name, e, env, _fenv, mono = rows[k]
        e, env = ints(e), ints(env)
        e[7] = k - 64
        env[3] = env[1]
        js.append(f'["{name}",[{",".join(map(str, e))}],[{",".join(map(str, env))}],{mono}]')
    begin, end = '/* gen_fmini_bank.py: begin */', '/* gen_fmini_bank.py: end */'
    page = root / 'web/editor.html'
    html = page.read_text()
    a, b = html.index(begin) + len(begin), html.index(end)
    html = html[:a] + '\n  const FMINI_ROWS = [' + ',\n    '.join(js) + '];\n  ' + html[b:]
    page.write_text(html)
    print(f'fmini bank: {NSLOT} mock presets -> {page}')


if __name__ == '__main__':
    main()
